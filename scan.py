"""List the decompiled source files, classify them and decide which ones are worth cleaning."""
import re
from pathlib import Path

import config
from textutil import estimate_tokens

# Namespaces / folders of well-known third-party code (it is rarely worth spending tokens on)
LIB_NS = {
    'UnityEngine', 'UnityEditor', 'Unity', 'System', 'Mono', 'Microsoft', 'Newtonsoft', 'TMPro', 'DG',
    'DOTween', 'Photon', 'ExitGames', 'Spine', 'FMOD', 'FMODUnity', 'ProtoBuf', 'LitJson', 'Zenject',
    'UniRx', 'Cinemachine', 'Rewired', 'Steamworks', 'Facebook', 'Firebase', 'Vuforia', 'ICSharpCode',
    'SharpCompress', 'Mirror', 'NUnit', 'JetBrains', 'Google', 'AOT',
}
LIB_NAME = re.compile(r'^(Photon|PUN|Pun[A-Z]|Spine|FMOD|Newtonsoft)')
GEN_NAME = re.compile(r'PrivateImplementationDetails|_003CModule_003E|\.g\.cs$|\.Designer\.cs$|Generated', re.I)
HINTS = re.compile(
    r'Manager|Controller|System|Service|Player|Enemy|Hero|Monster|Combat|Battle|Inventory|Dungeon|'
    r'Quest|Save|Game|Ability|Weapon|Effect|Skill', re.I)


def classify(rel, head):
    parts = rel.split('/')
    name = parts[-1]
    assembly = parts[0].lower()
    if GEN_NAME.search(name) or '<auto-generated' in head or '[GeneratedCode' in head:
        return 'generated'
    m = re.search(r'^\s*namespace\s+([\w.]+)', head, re.M)
    first_ns = m.group(1).split('.')[0] if m else ''
    folder = parts[1] if len(parts) > 2 else ''
    if assembly.endswith(('firstpass', 'plugins')) or first_ns in LIB_NS or folder in LIB_NS or LIB_NAME.match(name):
        return 'library'
    return 'game'


def score(category, name, text):
    if category != 'game':
        return 10 if category == 'library' else 0
    s = 100
    if re.search(r'\b(MonoBehaviour|ScriptableObject|NetworkBehaviour)\b', text[:6000]):
        s += 25
    if HINTS.search(name):
        s += 15
    n = len(text)
    if 2000 <= n <= 25000:
        s += 10
    elif n > 60000:
        s -= 10
    elif n < config.MIN_FILE_CHARS:
        s -= 40
    return s


def scan_sources(root, language):
    ext = '.cs' if language == 'csharp' else '.java'
    root = Path(root)
    files = []
    for p in sorted(root.rglob('*' + ext)):
        if not p.is_file() or p.name == 'AssemblyInfo.cs':
            continue
        rel = p.relative_to(root).as_posix()
        text = p.read_text(encoding='utf-8', errors='ignore')
        category = classify(rel, text[:4000])
        chars = len(text)
        parts = max(1, -(-chars // config.MAX_CHUNK_CHARS))
        est_in, est_out = estimate_tokens(chars, parts)
        files.append({
            'path': rel, 'chars': chars, 'lines': text.count('\n') + 1, 'category': category,
            'score': score(category, p.name, text), 'suggested': False, 'status': 'pending', 'note': '',
            'parts': parts, 'est_in': est_in, 'est_out': est_out, 'est_tokens': est_in + est_out,
            'tokens_in': 0, 'tokens_out': 0,
        })
    return files


def mark_suggested(files):
    """Pre-select the most valuable game files within the file and token budget."""
    budget, count = config.SUGGEST_TOKEN_BUDGET, 0
    for f in files:
        f['suggested'] = False
    for f in sorted(files, key=lambda f: -f['score']):
        if f['category'] != 'game' or f['chars'] < config.MIN_FILE_CHARS:
            continue
        if count >= config.SUGGEST_MAX_FILES:
            break
        if f['est_tokens'] > budget:
            continue
        f['suggested'] = True
        budget -= f['est_tokens']
        count += 1
    return sorted(files, key=lambda f: (-f['score'], f['path']))
