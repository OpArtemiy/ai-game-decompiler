PASSED = []


def check(name, cond, detail=''):
    if not cond:
        print(f'FAIL: {name} {detail}')
        sys.exit(1)
    PASSED.append(name)


PLAYER = '''using UnityEngine;

namespace Game
{
    public class Player : MonoBehaviour
    {
        public int Health = 100;
        private int num;

        public void TakeDamage(int amount)
        {
            int num2 = amount - 2;
            if (num2 < 0)
            {
                num2 = 0;
            }
            Health -= num2; // { brace in comment
            string s = "}{";
        }
    }
}
'''


def big_source(methods=60):
    body = ''.join(
        f'        public int Method{i}(int a)\n        {{\n            int num = a + {i};\n'
        f'            if (num > 5)\n            {{\n                return num;\n            }}\n\n            return 0;\n        }}\n\n'
        for i in range(methods))
    return 'using System;\n\nnamespace Game\n{\n    public class Big\n    {\n' + body + '    }\n}\n'


def fake_ask(prompt, model=None, max_tokens=0):
    """Pretends to be the AI: renames num -> count and adds a comment."""
    marker = 'Now clean ONLY the following part:\n\n'
    code = prompt.split(marker, 1)[1] if marker in prompt else prompt.split('\n\n', 1)[1]
    out = code.replace('num2', 'damage').replace('num', 'count')
    return '// cleaned\n' + out, {'input': 100, 'output': 120}


def bad_ask(prompt, model=None, max_tokens=0):
    return 'Sure! Here is the code:\n```csharp\nclass X {\n```', {'input': 10, 'output': 10}


def fake_decompiler(src, outdir, language):
    outdir = Path(outdir)
    (outdir / 'Game').mkdir(parents=True, exist_ok=True)
    (outdir / 'Game' / 'Player.cs').write_text(PLAYER * 3)
    (outdir / 'Game' / 'Big.cs').write_text(big_source())
    (outdir / 'GeneratedNetworkCode.cs').write_text('// <auto-generated>\n' + PLAYER * 3)
    (outdir / 'PhotonView.cs').write_text(PLAYER * 3)
    (outdir / 'Tiny.cs').write_text('class Tiny { }\n')


# ---- text helpers
check('strip_noise keeps newlines', strip_noise('a // x\n/* b\nc */ d\n').count('\n') == 3)
check('brace_balance ignores strings and comments', brace_balance(PLAYER) == 0)
check('brace_balance counts real braces', brace_balance('class A {') == 1)
names = public_names(PLAYER)
check('public_names finds members', {'Player', 'Health', 'TakeDamage'} <= names, names)
check('public_names skips private', 'num' not in names)
check('strip_fences', strip_fences('```csharp\nint a;\n```') == 'int a;')
check('fit_ends keeps the original line breaks', fit_ends('x', 'y\n\n') == 'x\n\n')

# ---- chunking
src = big_source(80)
parts = split_code(src, 3000)
check('split reconstructs the file exactly', ''.join(parts) == src)
check('split makes several parts', len(parts) > 3, len(parts))
check('parts respect the limit', all(len(p) <= 3200 for p in parts), [len(p) for p in parts][:5])
check('parts end at blank lines', all(p.endswith('\n\n') for p in parts[:-1]))
check('small file is not split', split_code(PLAYER, 12000) == [PLAYER])
check('header context contains class line', 'public class Big' in header_context(src))
long_lines = '\n'.join(['y' * 900] * 20)
check('hard split still reconstructs', ''.join(split_code(long_lines, 3000)) == long_lines)
check('single huge line ok', ''.join(split_code('x' * 5000, 1000)) == 'x' * 5000)

# ---- validation
good = '// cleaned\n' + PLAYER.replace('num2', 'damage')
check('validate accepts a good reply', validate_clean(PLAYER, good)[0], validate_clean(PLAYER, good))
check('validate rejects fences', not validate_clean(PLAYER, '```\n' + PLAYER)[0])
check('validate rejects renamed public member', not validate_clean(PLAYER, PLAYER.replace('TakeDamage', 'Hurt'))[0])
check('validate rejects broken braces', not validate_clean(PLAYER, PLAYER.replace('}\n    }\n}', '}\n    }'))[0])
check('validate rejects short reply', not validate_clean(PLAYER, PLAYER[:100])[0])
check('validate rejects empty', not validate_clean(PLAYER, '  ')[0])

